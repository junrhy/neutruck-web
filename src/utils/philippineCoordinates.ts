export function resolveCoordinates(locationName: string, plate: string): [number, number] {
  if (!locationName) return [14.5995, 120.9842]; // Default Manila
  const locLower = locationName.toLowerCase();

  // 1. Direct match or keyword match against dictionary keys
  for (const [key, coords] of Object.entries(PH_COORDINATES)) {
    if (locLower.includes(key)) {
      // Add slight jitter based on plate to avoid exact overlap of multiple trucks at same town/port
      let hash = 0;
      for (let i = 0; i < plate.length; i++) hash += plate.charCodeAt(i);
      const latJitter = ((hash % 10) - 5) * 0.005;
      const lngJitter = (((hash * 3) % 10) - 5) * 0.005;
      return [coords[0] + latJitter, coords[1] + lngJitter];
    }
  }

  // 2. Regional fallback matching by province or island group
  if (locLower.includes("bohol")) return [9.8500, 124.1435];
  if (locLower.includes("cebu")) return [10.3157, 123.8854];
  if (locLower.includes("leyte")) return [11.0064, 124.6075];
  if (locLower.includes("samar")) return [11.7753, 124.8864];
  if (locLower.includes("panay") || locLower.includes("iloilo")) return [10.6969, 122.5644];
  if (locLower.includes("negros")) return [10.6765, 122.9509];
  if (locLower.includes("palawan")) return [9.7392, 118.7353];
  if (locLower.includes("mindoro")) return [13.4117, 121.1803];
  if (locLower.includes("mindanao") || locLower.includes("davao")) return [7.1264, 125.6606];
  if (locLower.includes("bicol")) return [13.1391, 123.7438];

  // 3. Fallback hash mapping centered in Central Philippines (Bohol/Cebu Channel)
  let hash = 0;
  for (let i = 0; i < locationName.length; i++) hash = (hash * 31 + locationName.charCodeAt(i)) % 100;
  const fallbackLat = 9.8 + (hash % 5) * 0.1;
  const fallbackLng = 123.8 + (hash % 6) * 0.1;
  return [fallbackLat, fallbackLng];
}
